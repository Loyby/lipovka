"""Writes the shared (Android + iPhone) string table from the Android string resources.

The Android XML files stay the source of truth: the Android-only parts of the app (notifications, the widget)
read them as usual, and the shared screens read the same words from a generated Kotlin table, so both phones
say exactly the same.

python tools/strings_kt.py
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
OUT = ROOT / "shared/src/commonMain/kotlin/app/lipovka/ui/R.kt"


def unescape(s):
    s = s or ""
    # Android resource escapes; a plain string has no other meaning for them
    s = re.sub(r"\\(['\"@?])", r"\1", s)
    s = s.replace("\\n", "\n").replace("\\t", "\t")
    return s


def text(el):
    return unescape("".join(el.itertext()))


def load(path):
    root = ET.parse(path).getroot()
    strings, plurals, arrays = {}, {}, {}
    for el in root:
        name = el.get("name")
        if el.tag == "string":
            strings[name] = text(el)
        elif el.tag == "plurals":
            plurals[name] = {i.get("quantity"): text(i) for i in el}
        elif el.tag == "string-array":
            arrays[name] = [text(i) for i in el]
    return strings, plurals, arrays


def kt(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'


def qmap(d):
    return "mapOf(" + ", ".join(f"{kt(q)} to {kt(v)}" for q, v in d.items()) + ")"


def main():
    en_s, en_p, en_a = load(RES / "values/strings.xml")
    ru_s, ru_p, ru_a = load(RES / "values-ru/strings.xml")
    out = [
        "// Generated by tools/strings_kt.py from app/src/main/res/values*/strings.xml. Don't edit by hand.",
        "@file:Suppress(\"ObjectPropertyName\", \"ClassName\", \"unused\")",
        "",
        "package app.lipovka.ui",
        "",
        "/** The words of the shared screens, English and Russian, named as the Android string resources are. */",
        "object R {",
        "    object string {",
    ]
    for k, en in en_s.items():
        out.append(f"        val {k} = Sid({kt(en)}, {kt(ru_s.get(k, en))})")
    out.append("    }")
    out.append("")
    out.append("    object plurals {")
    for k, en in en_p.items():
        out.append(f"        val {k} = Pid({qmap(en)}, {qmap(ru_p.get(k, en))})")
    out.append("    }")
    out.append("")
    out.append("    object array {")
    for k, en in en_a.items():
        ru = ru_a.get(k, en)
        out.append(f"        val {k} = Aid(listOf({', '.join(map(kt, en))}), listOf({', '.join(map(kt, ru))}))")
    out.append("    }")
    out.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(en_s)} strings, {len(en_p)} plurals, {len(en_a)} arrays -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
